REPLACE  PROCEDURE /*VER.01*/ GPROD1_ETL.FLUSH_STG
    /*
    ###################################################################################################################################################################
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Version History
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    # 	Version 	|	Date        			|	Author					| 	Comments
    #	1.0        	|	20 October, 2023		|	Omar Hosny				|	Fisrt Cut.
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Examples:
    #  
    ###################################################################################################################################################################
    */
(
	IN		I_LAYER							VARCHAR(10),
	IN 		i_SOURCE_NAME  			VARCHAR(200), -- CAN NOT BE NULL
	IN 		i_TABLE_NAME  			VARCHAR(200), -- SET NULL TO FLUSH A TABLE ELSE WILL FLUSH A PROCESS WITHIN A BASE TABLE
	IN 		I_DELETE_CONFIRM		VARCHAR(50),
	IN 		I_RUN_ID 				BIGINT, -- AUTOGENERATED IF NOT GIVEN
	IN		I_SQL_SCRIPT_ID INTEGER,
	OUT  	O_DELETED_ROWS_COUNT	BIGINT,
	OUT  	O_RETURN_CODE  			INTEGER,
	OUT  	O_RETURN_MSG 			VARCHAR(5000),
	OUT 	O_RUN_ID 				BIGINT
)

BEGIN
		-- DECLARE VARIABLES
		DECLARE V_RETURN_CODE INTEGER DEFAULT 0;
    	DECLARE V_RETURN_MSG VARCHAR(5000) DEFAULT 'Process Completed Successfully';
    	DECLARE V_DBC_ROWS_COUNT BIGINT DEFAULT 0;
		DECLARE V_SCHEMA VARCHAR(40) DEFAULT 'GPROD1T';
		DECLARE V_EXEC_QUERY VARCHAR(250);
		DECLARE V_PROCESS_NAME VARCHAR(100);
		DECLARE	V_RUN_ID, V_DBC_RUN_ID BIGINT;
		DECLARE V_SQL_SCRIPT_ID INTEGER;
		DECLARE V_DBC_RETURN_CODE INTEGER;
		DECLARE V_DBC_RETURN_MSG VARCHAR(1000);
		DECLARE V_DELETE_CONFIRM_INPUT VARCHAR(250);
		
		DECLARE V_SOURCE_TABLE VARCHAR(150);
		DECLARE V_DELETED_ROWS_COUNT BIGINT;

		-- DECLARE EXIT HANDLER
		DECLARE EXIT HANDLER FOR SQLEXCEPTION
	        BEGIN 	
		        SET V_RETURN_CODE = SQLCODE;
				GET DIAGNOSTICS EXCEPTION 1 V_RETURN_MSG = MESSAGE_TEXT; 			
			
				SET o_RETURN_CODE  = V_RETURN_CODE;
				SET o_RETURN_MSG = V_RETURN_MSG;
	        END;
		
		MAINBLOCK:
		BEGIN
			-- SET SQL SCRIPT ID
			SET V_SQL_SCRIPT_ID = COALESCE(I_SQL_SCRIPT_ID, 0);
			
			-- SET RUN ID
			IF I_RUN_ID IS NULL THEN 
				SELECT GPROD1_ETL.GENERATE_RUN_ID()
				into V_RUN_ID;
			ELSE 	
				SET V_RUN_ID= I_RUN_ID;
			END IF;
			
			-- VALIDATE ON LAYER
			IF I_LAYER NOT IN ('STG', 'SRCI') THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'LAYER PARAMETER CAN ONLY BE ONE OF THOSE VALUES (STG, SRCI)';
				LEAVE MAINBLOCK;
			END IF;
			
			-- VALIDATE ON SOURCE_NAME
			IF i_SOURCE_NAME IS NULL THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'SOURCE_NAME CAN NOT BE NULL';
				LEAVE MAINBLOCK;
			END IF;
			
			-- IF TABLE NAME IS NOT NULL THEN VALIDATE IT EXISTS FOR THIS SOURCE THEN DEVELOP QUERY
			-- OTHERWISE VALIDATE THAT THE USER CONFIRMS THAT THEY WANT TO DELETE ALL STG TABLES FOR THIS SOURCE
			SET V_SCHEMA = V_SCHEMA || '_' || I_LAYER;
			
			IF i_TABLE_NAME IS NOT NULL THEN
				
				-- CHECK IF TABLE EXISTS
				SEL TOP 1 TABLE_NAME FROM GPROD1_ETL.SOURCE_SYSTEM_TABLES WHERE SOURCE_NAME = i_SOURCE_NAME AND TABLE_NAME = i_TABLE_NAME INTO V_SOURCE_TABLE;
				IF V_SOURCE_TABLE IS NULL THEN
					SET V_RETURN_CODE = -1;
					SET V_RETURN_MSG = 'TABLE_NAME DOES NOT EXIST IN METADATA FOR ' || i_SOURCE_NAME || ' SOURCE';
					LEAVE MAINBLOCK;
				
				-- OTHERWISE EXECUTE QUERY
				ELSE 
					-- DEVELOP QUERY TO DELETE THIS TABLE
					SET V_EXEC_QUERY =  'DEL FROM ' || V_SCHEMA || '.' || V_SOURCE_TABLE || ';';
					SET V_PROCESS_NAME = I_LAYER || '_' || i_TABLE_NAME;
					CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(V_EXEC_QUERY,V_SQL_SCRIPT_ID,V_RUN_ID,'FLUSH',V_PROCESS_NAME,NULL /*LOAD_ID*/,1/*1 log or 0 don't*/,V_DBC_RETURN_CODE,V_DBC_RETURN_MSG,V_DBC_ROWS_COUNT,v_dbc_run_id);
					IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
						LEAVE MainBlock;
					ELSE
						SET V_DELETED_ROWS_COUNT = V_DBC_ROWS_COUNT;
					END IF;
					
				END IF;
			
			ELSE
				
				-- VALIDATE THAT THE USER CONFIRMS TO DELETE THE SOURCE
				SET V_DELETE_CONFIRM_INPUT = 'FLUSH ' || I_LAYER || ' ' || i_SOURCE_NAME;
				IF I_DELETE_CONFIRM IS NULL OR I_DELETE_CONFIRM <> V_DELETE_CONFIRM_INPUT THEN
					SET V_RETURN_CODE = -1;
					SET V_RETURN_MSG = 'TO DELETE ALL STAGING TABLES, SET THE DELETE_CONFIRM INPUT PARAMETER TO ''' || V_DELETE_CONFIRM_INPUT || '''';
					LEAVE MAINBLOCK;
				
				-- OTHERWISE EXECUTE QUERY FOR ALL TABLES
				ELSE
					-- DEVELOP QUERY TO DELETE ALL TABLES OF THIS SOURCE
					SET V_DELETED_ROWS_COUNT = 0;
					FOR X AS X1 CURSOR FOR
						SEL * 
						FROM GPROD1_ETL.SOURCE_SYSTEM_TABLES X
						WHERE SOURCE_NAME = i_SOURCE_NAME
						AND NOT EXISTS(SEL 1 FROM GPROD1_ETL.SOURCE_SYSTEMS Y WHERE Y.SOURCE_NAME = i_SOURCE_NAME AND (X.TABLE_NAME = Y.REJECTION_TABLE_NAME OR X.TABLE_NAME = Y.BUSINESS_RULES_TABLE_NAME))
					DO
						SET V_SQL_SCRIPT_ID = V_SQL_SCRIPT_ID + 1;
						SET V_PROCESS_NAME = I_LAYER || '_' || X.TABLE_NAME;
						SET V_EXEC_QUERY =  'DEL FROM ' || V_SCHEMA || '.' || X.TABLE_NAME || ';';
						
						CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(V_EXEC_QUERY,V_SQL_SCRIPT_ID,V_RUN_ID,'FLUSH',V_PROCESS_NAME,NULL /*LOAD_ID*/,1/*1 log or 0 don't*/,V_DBC_RETURN_CODE,V_DBC_RETURN_MSG,V_DBC_ROWS_COUNT,v_dbc_run_id);
						IF V_DBC_RETURN_CODE <> 0 THEN
							SET V_RETURN_CODE = V_DBC_RETURN_CODE;
							SET V_RETURN_MSG = V_DBC_RETURN_MSG;
							LEAVE MainBlock;
						END IF;
						SET V_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT + V_DBC_ROWS_COUNT;
						
					END FOR;
				END IF;
				
			END IF;

		END; --MAINBLOCK
		
		SET O_RETURN_CODE = V_RETURN_CODE;
    	SET O_RETURN_MSG = V_RETURN_MSG;
		SET O_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT;
		SET O_RUN_ID = V_RUN_ID;		
		
END; -- PROCEDURE