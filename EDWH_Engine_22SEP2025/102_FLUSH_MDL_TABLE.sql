REPLACE  PROCEDURE /*VER.01*/ GPROD1_ETL.FLUSH_MDL_TABLE
    /*
    ###################################################################################################################################################################
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Version History
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    # 	Version 	|	Date        			|	Author					| 	Comments
    #	1.0        	|	25 October, 2023		|	Omar Hosny				|	Fisrt Cut.
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Examples:
    #  
    ###################################################################################################################################################################
    */
(
IN 		i_TABLE_NAME  			VARCHAR(200), -- CAN NOT BE NULL
IN 		i_PROCESS_NAME  			VARCHAR(200), -- SET NULL TO FLUSH A TABLE ELSE WILL FLUSH A PROCESS WITHIN A BASE TABLE
IN 		I_DELETE_CONFIRM		VARCHAR(50),
IN 		I_RUN_ID 				BIGINT, -- AUTOGENERATED IF NOT GIVEN
IN		I_SQL_SCRIPT_ID INTEGER,
OUT  	O_DELETED_ROWS_COUNT	BIGINT,
OUT  	O_RETURN_CODE  			INTEGER,
OUT  	O_RETURN_MSG 			VARCHAR(5000),
OUT 	O_RUN_ID 				BIGINT
)

BEGIN
		-- DECLARE VARIABLES
		DECLARE V_RETURN_CODE INTEGER DEFAULT 0;
    	DECLARE V_RETURN_MSG VARCHAR(5000) DEFAULT 'Process Completed Successfully';
    	DECLARE V_DBC_ROWS_COUNT BIGINT DEFAULT 0;
		DECLARE V_BASE_SCHEMA VARCHAR(20) DEFAULT 'GPROD1T_BASE';
		DECLARE V_EXEC_QUERY VARCHAR(250);
		DECLARE V_PROCESS_NAME VARCHAR(100);
		DECLARE	V_RUN_ID, V_DBC_RUN_ID BIGINT;
		DECLARE V_SQL_SCRIPT_ID INTEGER;
		DECLARE V_DBC_RETURN_CODE INTEGER;
		DECLARE V_DBC_RETURN_MSG VARCHAR(1000);
		DECLARE V_DELETE_CONFIRM_INPUT VARCHAR(250);
		

		-- DECLARE EXIT HANDLER
		DECLARE EXIT HANDLER FOR SQLEXCEPTION
	        BEGIN 	
		        SET V_RETURN_CODE = SQLCODE;
				GET DIAGNOSTICS EXCEPTION 1 V_RETURN_MSG = MESSAGE_TEXT; 			
			
				SET o_RETURN_CODE  = V_RETURN_CODE;
				SET o_RETURN_MSG = V_RETURN_MSG;
	        END;

		MAINBLOCK:
		BEGIN
			-- SET SQL SCRIPT ID
			SET V_SQL_SCRIPT_ID = COALESCE(I_SQL_SCRIPT_ID, 0);
			
			-- SET RUN ID
			IF I_RUN_ID IS NULL THEN 
				SELECT GPROD1_ETL.GENERATE_RUN_ID()
				into V_RUN_ID;
			ELSE 	
				SET V_RUN_ID= I_RUN_ID;
			END IF;
			
			-- VALIDATE ON TABLE_NAME
			IF i_TABLE_NAME IS NULL THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'TABLE_NAME CAN NOT BE NULL';
				LEAVE MAINBLOCK;
			END IF;
				
			
			-- SET AND CONTROL THE CONFIRMATION MESSAGE TO DELETE THE TABLE
			SET V_DELETE_CONFIRM_INPUT = 'FLUSH CORE ' || i_TABLE_NAME;
			
			-- DEVELOP QUERY
			IF i_PROCESS_NAME IS NOT NULL THEN
				SET V_PROCESS_NAME = 'FLUSH_BASE_' || i_PROCESS_NAME;
				SET V_EXEC_QUERY = 'DEL FROM ' || V_BASE_SCHEMA || '.' || i_TABLE_NAME || ' WHERE COALESCE(UPDATE_PROCESS_NAME, PROCESS_NAME) = ''' || i_PROCESS_NAME || ''';';
			ELSEIF  i_PROCESS_NAME IS NULL AND (I_DELETE_CONFIRM IS NULL OR I_DELETE_CONFIRM <> V_DELETE_CONFIRM_INPUT ) THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'TO DELETE A BASE TABLE, SET THE DELETE_CONFIRM INPUT PARAMETER TO ''' || V_DELETE_CONFIRM_INPUT || '''';
				LEAVE MAINBLOCK;
			ELSE
				SET V_PROCESS_NAME = 'FLUSH_BASE_' || I_TABLE_NAME;
				SET V_EXEC_QUERY = 'DEL FROM ' || V_BASE_SCHEMA || '.' || i_TABLE_NAME || ';';
			END IF;
			
			-- EXECUTE QUERY
			CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(V_EXEC_QUERY,V_SQL_SCRIPT_ID,V_RUN_ID,'FLUSH',V_PROCESS_NAME,NULL /*LOAD_ID*/,1/*1 log or 0 don't*/,V_DBC_RETURN_CODE,V_DBC_RETURN_MSG,V_DBC_ROWS_COUNT,v_dbc_run_id);
			IF V_DBC_RETURN_CODE <> 0 THEN
				SET V_RETURN_CODE = V_DBC_RETURN_CODE;
				SET V_RETURN_MSG = V_DBC_RETURN_MSG;
				LEAVE MainBlock;
			END IF;
		
		-- MAINBLOCK
		END; 
		
		SET O_RETURN_CODE = V_RETURN_CODE;
    	SET O_RETURN_MSG = V_RETURN_MSG;
		SET O_DELETED_ROWS_COUNT = V_DBC_ROWS_COUNT;
		SET O_RUN_ID = V_RUN_ID;		
END;