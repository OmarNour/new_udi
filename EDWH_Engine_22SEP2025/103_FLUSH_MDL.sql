REPLACE  PROCEDURE /*VER.01*/ GPROD1_ETL.FLUSH_MDL
    /*
    ###################################################################################################################################################################
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Version History
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    # 	Version 	|	Date        			|	Author					| 	Comments
    #	1.0        	|	25 October, 2023		|	Omar Hosny				|	Fisrt Cut.
	#	2.0        	|	25 October, 2023		|	Omar Hosny				|	ADDING INPUT SQL_SCRIPT_ID TO BE USED IN OTHER PROCEDURES THE EXEC_SCRIPT_LOGS.
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Examples:
    #  
    ###################################################################################################################################################################
    */
(
	IN		i_SOURCE_NAME			VARCHAR(50), -- CAN NOT BE NULL
	IN 		i_TABLE_NAME  			VARCHAR(200), -- TARGET TABLE
	IN 		i_PROCESS_NAME  			VARCHAR(200), -- 
	IN 		I_DELETE_CONFIRM		VARCHAR(50),
	IN		I_SQL_SCRIPT_ID INTEGER,
	IN 		I_RUN_ID 				BIGINT, -- AUTOGENERATED IF NOT GIVEN
	OUT  	O_DELETED_ROWS_COUNT	BIGINT,
	OUT  	O_RETURN_CODE  			INTEGER,
	OUT  	O_RETURN_MSG 			VARCHAR(5000),
	OUT 	O_RUN_ID 				BIGINT
)

BEGIN
		-- DECLARE VARIABLES
		DECLARE V_RETURN_CODE INTEGER DEFAULT 0;
    	DECLARE V_RETURN_MSG VARCHAR(5000) DEFAULT 'Process Completed Successfully';
		DECLARE V_PROCESS_NAME VARCHAR(100);
		DECLARE V_RUN_ID, V_DBC_RUN_ID BIGINT;
		DECLARE V_SQL_SCRIPT_ID INTEGER;
		DECLARE V_DBC_RETURN_CODE INTEGER;
		DECLARE V_DBC_RETURN_MSG VARCHAR(1000);
		DECLARE V_DBC_DELETED_ROWS_COUNT BIGINT;
		DECLARE V_DELETE_CONFIRM_INPUT VARCHAR(250);
		DECLARE V_DELETED_ROWS_COUNT BIGINT;
		
		
		DECLARE EXIT HANDLER FOR SQLEXCEPTION
	    BEGIN 	
	        SET V_RETURN_CODE = SQLCODE;
			GET DIAGNOSTICS EXCEPTION 1 V_RETURN_MSG = MESSAGE_TEXT; 			
		
			SET o_RETURN_CODE  = V_RETURN_CODE;
			SET o_RETURN_MSG = V_RETURN_MSG;
	    END;
		
		MAINBLOCK:
		BEGIN
			-- SET RUN ID
			IF I_RUN_ID IS NULL THEN 
				SELECT GPROD1_ETL.GENERATE_RUN_ID()
				into V_RUN_ID;
			ELSE 	
				SET V_RUN_ID= I_RUN_ID;
			END IF;
			
			-- VALIDATE THAT THE SOURCE NAME IS NOT NULL
			IF i_SOURCE_NAME IS NULL THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'SOURCE_NAME CAN NOT BE NULL';
				LEAVE MAINBLOCK;
			END IF;
			
			-- VALIDATE THAT WHEN THE USER ASKS TO DELETE A SOURCE THEY NEED TO SET THE DELETE CONFIRM PARAMETER
			SET V_DELETE_CONFIRM_INPUT = 'DELETE ' || i_SOURCE_NAME;			
			IF i_TABLE_NAME IS NULL AND i_PROCESS_NAME IS NULL AND (I_DELETE_CONFIRM IS NULL OR I_DELETE_CONFIRM <> V_DELETE_CONFIRM_INPUT ) THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'TO DELETE A SOURCE, SET THE DELETE_CONFIRM INPUT PARAMETER TO ''' || V_DELETE_CONFIRM_INPUT || '''';
				LEAVE MAINBLOCK;
			END IF;
				
			
			-- LOOP ON PROCESS TABLE TO DELETE ALL RELEVANT PROCESSES
			SET V_SQL_SCRIPT_ID = COALESCE(I_SQL_SCRIPT_ID, 0);
			SET V_DELETED_ROWS_COUNT = 0;
			FOR X AS X1 CURSOR FOR 
				SEL 
						*
					FROM GPROD1_ETL.PROCESS
					WHERE TGT_LAYER = 'CORE'
					AND SOURCE_NAME = i_SOURCE_NAME
					AND (TGT_TABLE = i_TABLE_NAME OR i_TABLE_NAME IS NULL)
					AND  (PROCESS_NAME = i_PROCESS_NAME OR i_PROCESS_NAME IS NULL)
					
				DO
					
					SET V_SQL_SCRIPT_ID = V_SQL_SCRIPT_ID + 1;
					CALL GPROD1_ETL.FLUSH_MDL_TABLE(
																								X.TGT_TABLE, 
																								X.PROCESS_NAME, 
																								NULL, -- CONFIRM DELETE
																								V_RUN_ID, 
																								V_SQL_SCRIPT_ID, 
																								V_DBC_DELETED_ROWS_COUNT, 
																								V_DBC_RETURN_CODE, 
																								V_DBC_RETURN_MSG, 
																								V_DBC_RUN_ID
																						);
					SET V_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT + V_DBC_DELETED_ROWS_COUNT;
					IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
						LEAVE MainBlock;
					END IF;
					
			END FOR;
		
		END; -- MAINBLOCK
		
		
		SET O_RETURN_CODE = V_RETURN_CODE;
    	SET O_RETURN_MSG = V_RETURN_MSG;
		SET O_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT;
		SET O_RUN_ID = V_RUN_ID;	

END;