REPLACE  PROCEDURE /*VER.01*/ GPROD1_ETL.FLUSH_SOURCE
	    /*
    ###################################################################################################################################################################
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Version History
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    # 	Version 		|	Date        						|	Author					| 	Comments
 \   #	1.0        	|	11 December, 2023		|	Omar Hosny				|	FLUSH STG, SRCI, MDL OR ALL SOURCE
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Examples:
	    #  CALL GPROD1_ETL.FLUSH_SOURCE
		(
			'NAFEZA',
			NULL, 
			'ALL',
			'I CONFIRM TO FLUSH NAFEZA',
			324732058237,
			A,
			B,
			C,
			D
		);
    ###################################################################################################################################################################
    */
	
	(
		IN		i_SOURCE_NAME				VARCHAR(50), -- CAN NOT BE NULL
		IN 		I_PROCESS_NAME  			VARCHAR(200), 
		IN 		I_LAYER  							VARCHAR(20), --(STG, SRCI, MDL, ALL)
		IN 		I_DELETE_CONFIRM			VARCHAR(50),
		IN 		I_RUN_ID 							BIGINT, -- AUTOGENERATED IF NOT GIVEN
		OUT  	O_DELETED_ROWS_COUNT	BIGINT,
		OUT  	O_RETURN_CODE  			INTEGER,
		OUT  	O_RETURN_MSG 				VARCHAR(5000),
		OUT 	O_RUN_ID 							BIGINT
	)

	BEGIN
		-- DECLARE VARIABLES
		DECLARE V_RETURN_CODE INTEGER DEFAULT 0;
    	DECLARE V_RETURN_MSG VARCHAR(5000) DEFAULT 'Process Completed Successfully';
		DECLARE V_SOURCE_NAME VARCHAR(200);
		DECLARE V_PROCESS_NAME VARCHAR(200);
		DECLARE V_RUN_ID, V_DBC_RUN_ID BIGINT;
		DECLARE V_SQL_SCRIPT_ID INTEGER;
		DECLARE V_DBC_RETURN_CODE INTEGER;
		DECLARE V_DBC_RETURN_MSG VARCHAR(1000);
		DECLARE V_DBC_DELETED_ROWS_COUNT BIGINT;
		DECLARE V_DELETE_CONFIRM_INPUT VARCHAR(250);
		DECLARE V_DELETED_ROWS_COUNT BIGINT;
	
		DECLARE EXIT HANDLER FOR SQLEXCEPTION
	    BEGIN 	
	        SET V_RETURN_CODE = SQLCODE;
			GET DIAGNOSTICS EXCEPTION 1 V_RETURN_MSG = MESSAGE_TEXT; 			
		
			SET o_RETURN_CODE  = V_RETURN_CODE;
			SET o_RETURN_MSG = V_RETURN_MSG;
	    END;
		
		MAINBLOCK:
		BEGIN
			-- SET RUN ID
			IF I_RUN_ID IS NULL THEN 
				SELECT GPROD1_ETL.GENERATE_RUN_ID()
				into V_RUN_ID;
			ELSE 	
				SET V_RUN_ID= I_RUN_ID;
			END IF;
			
			-- VALIDATE THAT THE SOURCE NAME IS NOT NULL
			SEL 
				SOURCE_NAME 
			FROM GPROD1_ETL.SOURCE_SYSTEMS 
			WHERE SOURCE_NAME = i_SOURCE_NAME OR i_SOURCE_NAME IS NULL 
			INTO V_SOURCE_NAME;
			
			--SEL SOURCE_NAME FROM GPROD1_ETL.SOURCE_SYSTEMS WHERE SOURCE_NAME = i_SOURCE_NAME OR i_SOURCE_NAME IS NULL INTO V_SOURCE_NAME;
			IF V_SOURCE_NAME IS NULL THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'EITHER SOURCE_NAME IS NULL OR DOES NOT EXIST IN METADATA';
				LEAVE MAINBLOCK;
			END IF;
			
			IF I_LAYER NOT IN  ('STG', 'SRCI', 'MDL', 'ALL') THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'FLUSH_MODE MUST BE ONE OF THOSE VALUES (STG, SRCI, MODEL, ALL)';
				LEAVE MAINBLOCK;
			END IF;
			
			
			IF i_PROCESS_NAME IS NOT NULL THEN
				-- VALIDATE THE PROCESS EXISTS IN METADATA
				SEL PROCESS_NAME FROM GPROD1_ETL.PROCESS WHERE PROCESS_NAME = i_PROCESS_NAME INTO V_PROCESS_NAME;
				
				--PROCESS DOESN'T EXIST IN METADATA THEN WRONG USER INPUT
				IF V_PROCESS_NAME IS NULL THEN
					SET V_RETURN_CODE = -1;
					SET V_RETURN_MSG = 'PROCESS_NAME DOES NOT EXIST IN METADATA';
					LEAVE MAINBLOCK;
				--PROCESS EXISTS IN METADATA THEN FLUSH THE PROCESS
				ELSE
					CALL GPROD1_ETL.FLUSH_MDL(
						V_SOURCE_NAME,
						NULL, -- TARGET TABLE
						V_PROCESS_NAME, -- 
						NULL, -- CONFIRM DELETE DOESN'T NEED TO BE GIVEN WHEN DELETING A PROCESS
						0, --I_SQL_SCRIPT_ID
						V_RUN_ID, -- AUTOGENERATED IF NOT GIVEN
						V_DBC_DELETED_ROWS_COUNT, 
						V_DBC_RETURN_CODE, 
						V_DBC_RETURN_MSG, 
						V_DBC_RUN_ID
					);
					IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
					END IF;
					LEAVE MAINBLOCK;
				END IF;
			END IF;
			
			
			
			SET V_DELETE_CONFIRM_INPUT = 'I CONFIRM TO FLUSH ' || i_SOURCE_NAME;
			IF I_DELETE_CONFIRM IS NULL OR I_DELETE_CONFIRM <> V_DELETE_CONFIRM_INPUT THEN
				SET V_RETURN_CODE = -1;
				SET V_RETURN_MSG = 'TO DELETE A SOURCE, SET THE DELETE_CONFIRM INPUT PARAMETER TO ''' || V_DELETE_CONFIRM_INPUT || '''';
				LEAVE MAINBLOCK;
			END IF;
			
			SET V_SQL_SCRIPT_ID = 0;
			
			
			-- STEP 1: FLUSH STG
			IF I_LAYER IN ('STG', 'ALL') THEN
				CALL GPROD1_ETL.FLUSH_STG(
					'STG',
					V_SOURCE_NAME, -- CAN NOT BE NULL
					NULL, -- SET NULL TO FLUSH A TABLE ELSE WILL FLUSH A PROCESS WITHIN A BASE TABLE
					'FLUSH STG ' || V_SOURCE_NAME,
					V_RUN_ID,
					V_SQL_SCRIPT_ID,
					V_DBC_DELETED_ROWS_COUNT, 
					V_DBC_RETURN_CODE, 
					V_DBC_RETURN_MSG, 
					V_DBC_RUN_ID
				);
				
				IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
				END IF;
				
			END IF;
			
			-- UPDATE THE SQL SCRIPT ID
			SEL 
				MAX(SQL_SCRIPT_SEQ) + 1 
			FROM GPROD1_ETL.EXEC_SCRIPT_LOGS 
			WHERE RUN_ID = V_RUN_ID
			INTO V_SQL_SCRIPT_ID;
			--SET V_SQL_SCRIPT_ID = SEL MAX(SQL_SCRIPT_ID) + 1 FROM EXEC_SOURCE_LOGS WHERE RUN_ID = V_RUN_ID;
			
			-- STEP 2: FLUSH SRCI
			IF I_LAYER IN ('SRCI', 'ALL') THEN
				CALL GPROD1_ETL.FLUSH_MDL(
						i_SOURCE_NAME,
						NULL, -- TARGET TABLE
						V_PROCESS_NAME, -- 
						NULL, -- CONFIRM DELETE DOESN'T NEED TO BE GIVEN WHEN DELETING A PROCESS
						0, --I_SQL_SCRIPT_ID
						V_RUN_ID, -- AUTOGENERATED IF NOT GIVEN
						V_DBC_DELETED_ROWS_COUNT, 
						V_DBC_RETURN_CODE, 
						V_DBC_RETURN_MSG, 
						V_DBC_RUN_ID
					);
				IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
				END IF;
			END IF;
			
			-- UPDATE THE SQL SCRIPT ID
			SEL 
				MAX(SQL_SCRIPT_SEQ) + 1 
			FROM GPROD1_ETL.EXEC_SCRIPT_LOGS 
			WHERE RUN_ID = V_RUN_ID
			INTO V_SQL_SCRIPT_ID;
			
			--SET V_SQL_SCRIPT_ID = SEL MAX(SQL_SCRIPT_ID) + 1 FROM EXEC_SOURCE_LOGS WHERE RUN_ID = V_RUN_ID;
			
			-- STEP 3: FLUSH MODEL
			IF I_LAYER IN ('MDL', 'ALL') THEN
				CALL GPROD1_ETL.FLUSH_MDL(
						V_SOURCE_NAME,
						NULL, -- TARGET TABLE
						NULL, -- 
						'DELETE ' || V_SOURCE_NAME, -- CONFIRM DELETE DOESN'T NEED TO BE GIVEN WHEN DELETING A PROCESS
						V_SQL_SCRIPT_ID, --I_SQL_SCRIPT_ID
						V_RUN_ID, -- AUTOGENERATED IF NOT GIVEN
						V_DBC_DELETED_ROWS_COUNT, 
						V_DBC_RETURN_CODE, 
						V_DBC_RETURN_MSG, 
						V_DBC_RUN_ID
					);
					IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
					END IF;
			END IF;
			
			
			
			-- UPDATE THE SQL SCRIPT ID
			SEL 
				MAX(SQL_SCRIPT_SEQ) + 1 
			FROM GPROD1_ETL.EXEC_SCRIPT_LOGS 
			WHERE RUN_ID = V_RUN_ID
			INTO V_SQL_SCRIPT_ID;
			
			-- STEP 4: DELETE SOURCE LOGS
			CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(
				'DEL FROM GPROD1_ETL.EXEC_SOURCE_LOGS WHERE SOURCE_NAME = ''' || V_SOURCE_NAME || ''';',
				V_SQL_SCRIPT_ID,
				V_RUN_ID,
				'FLUSH',
				'DELETE SOURCE LOGS',
				NULL /*LOAD_ID*/,
				1/*1 log or 0 don't*/,
				V_DBC_RETURN_CODE,
				V_DBC_RETURN_MSG,
				V_DBC_DELETED_ROWS_COUNT,
				v_dbc_run_id
			);
			
			IF V_DBC_RETURN_CODE <> 0 THEN
				SET V_RETURN_CODE = V_DBC_RETURN_CODE;
				SET V_RETURN_MSG = V_DBC_RETURN_MSG;
			END IF;
			
			-- STEP 5: UPDATE PROCESSED COLUMN IN CDC_AUDIT
			CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(
				'UPDATE GPROD1_ETL.CDC_AUDIT SET PROCESSED = 0 WHERE SOURCE_NAME = ''' || V_SOURCE_NAME || ''';',
				V_SQL_SCRIPT_ID + 1,
				V_RUN_ID,
				'FLUSH',
				'UPDATE PROCESSED COLUMN IN CDC_AUDIT',
				NULL /*LOAD_ID*/,
				1/*1 log or 0 don't*/,
				V_DBC_RETURN_CODE,
				V_DBC_RETURN_MSG,
				V_DBC_DELETED_ROWS_COUNT,
				v_dbc_run_id
			);
			
			IF V_DBC_RETURN_CODE <> 0 THEN
				SET V_RETURN_CODE = V_DBC_RETURN_CODE;
				SET V_RETURN_MSG = V_DBC_RETURN_MSG;
			END IF;
			
		END; --MAINBLOCK
		
		SET O_RETURN_CODE = V_RETURN_CODE;
    	SET O_RETURN_MSG = V_RETURN_MSG;
		SET O_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT;
		SET O_RUN_ID = V_RUN_ID;	
		
	END; --PROCEDURE