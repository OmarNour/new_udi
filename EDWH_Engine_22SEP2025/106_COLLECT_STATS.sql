REPLACE  PROCEDURE /*VER.01*/ GPROD1_ETL.COLLECT_STATS
    /*
    ###################################################################################################################################################################
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Version History
    ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    # 	Version 	|	Date        			|	Author					| 	Comments
    #	1.0        	|	20 October, 2023		|	Omar Hosny				|	GENERATES AND EXECUTES COLLECT STATS STATEMENTS FOR ALL ACTIVE SOURCES, LAYERS AND TABELS UNLESS YOU SPECIFY OTHERWISE IN THE INPUT PARAMETERS.
    #   2.0        	|	17 DEC, 2023		    |	AHMED EHAB				| ENHANCMENT IN QUERY TO GET DATA ONCE DEPENDING ON LAYER_NAME OR SOURCE_NAME OR TABLE_NAME 
   ------------------------------------------------------------------------------------------------------------------------------------------------------------------
    #  Examples:
      	CALL GPROD1_ETL.COLLECT_STATS('STG', 'NAFEZA', NULL, 1002003004002, NULL, A,B,C);
		CALL GPROD1_ETL.COLLECT_STATS('CORE', 'NAFEZA', NULL, 1002003004003, NULL, A,B,C);
		CALL GPROD1_ETL.COLLECT_STATS('SRCI', 'NAFEZA', 'NAFEZA_CustomsSystemValidPair', 1002003004004, NULL, A,B,C);
		CALL GPROD1_ETL.COLLECT_STATS('BKEY', 'NAFEZA', 'BKEY_2_LOCTR', 1002003004005, NULL, A,B,C);
    ###################################################################################################################################################################
    */
(
	IN		I_LAYER							VARCHAR(10), --(STG, SRCI, BASE, UTLFW)
	IN 		i_SOURCE_NAME  			VARCHAR(200), -- CAN NOT BE NULL
	IN 		i_TABLE_NAME  			VARCHAR(200), -- USE IF YOU WANT TO COLLECT STATS FOR SPECIFIC TABLE, OTHERWISE SET TO NULL
	IN 		I_RUN_ID 				BIGINT, -- AUTOGENERATED IF NOT GIVEN
	IN		I_SQL_SCRIPT_ID INTEGER,
	OUT  	O_RETURN_CODE  			INTEGER,
	OUT  	O_RETURN_MSG 			VARCHAR(5000),
	OUT 	O_RUN_ID 				BIGINT
)
BEGIN
	-- DECLARE VARIABLES
	DECLARE V_RETURN_CODE, V_DBC_RETURN_CODE INTEGER DEFAULT 0;
	DECLARE V_RETURN_MSG, V_DBC_RETURN_MSG VARCHAR(5000) DEFAULT 'Process Completed Successfully';
	DECLARE	V_RUN_ID, V_DBC_RUN_ID BIGINT;
	DECLARE V_SQL_SCRIPT_ID INTEGER;
	DECLARE V_DBC_ROWS_COUNT INTEGER;
	
-- DECLARE EXIT HANDLER
	DECLARE EXIT HANDLER FOR SQLEXCEPTION
        BEGIN 	
	        SET V_RETURN_CODE = SQLCODE;
			GET DIAGNOSTICS EXCEPTION 1 V_RETURN_MSG = MESSAGE_TEXT; 			
		
			SET o_RETURN_CODE  = V_RETURN_CODE;
			SET o_RETURN_MSG = V_RETURN_MSG;
        END;
		
	MAINBLOCK:
	BEGIN
		-- SET SQL SCRIPT ID
		SET V_SQL_SCRIPT_ID = COALESCE(I_SQL_SCRIPT_ID, 0);
		
		-- SET RUN ID
		IF I_RUN_ID IS NULL THEN 
			SELECT GPROD1_ETL.GENERATE_RUN_ID()
			into V_RUN_ID;
		ELSE 	
			SET V_RUN_ID= I_RUN_ID;
		END IF;
	        FOR X AS X1 CURSOR FOR
				SEL DISTINCT 
							A.LYR_DB
							, A.TABLE_NAME 
							, A.COLLECT_STATS AS COLLECT_STATS_QUERY  
							,P.TGT_LAYER
				FROM GPROD1_ETL.V_collect_stats A
						INNER JOIN  GPROD1_ETL.V_PROCESS P 
						ON A.TABLE_NAME = P.TGT_TABLE
						AND A.LYR_DB= P.TGT_DB
				WHERE (P.TGT_LAYER = I_LAYER OR I_LAYER IS NULL )
				AND ( P.SOURCE_NAME =  i_SOURCE_NAME OR i_SOURCE_NAME IS NULL )
				AND (P.TGT_TABLE  = i_TABLE_NAME OR i_TABLE_NAME IS NULL)
			
			DO
				CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(
					X.COLLECT_STATS_QUERY,
					V_SQL_SCRIPT_ID,
					V_RUN_ID,
					'COLLECT STATS',
					X.LYR_DB|| '.' || X.TABLE_NAME,
					NULL /*LOAD_ID*/,
					1/*1 log or 0 don't*/,
					V_DBC_RETURN_CODE,
					V_DBC_RETURN_MSG,
					V_DBC_ROWS_COUNT,
					v_dbc_run_id
				);	
				
				IF V_DBC_RETURN_CODE <> 0 THEN
					SET V_RETURN_CODE = V_DBC_RETURN_CODE;
					SET V_RETURN_MSG = V_DBC_RETURN_MSG;
					LEAVE MainBlock;
				END IF;
				
				SET V_SQL_SCRIPT_ID = V_SQL_SCRIPT_ID + 1;
			END FOR;
	END; --MAINBLOCK
	
	SET O_RETURN_CODE = V_RETURN_CODE;
	SET O_RETURN_MSG = V_RETURN_MSG;
	SET O_RUN_ID = V_RUN_ID;		
	
END;
