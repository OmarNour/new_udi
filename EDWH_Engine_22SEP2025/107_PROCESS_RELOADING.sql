REPLACE  PROCEDURE /*VER.01*/ GPROD1_ETL.
PROCESS_RELOADING

    (
    IN 		i_PROCESS_NAME  			VARCHAR(200),
    IN 		i_AFFECTED_TABLES  		VARCHAR(2000),
    IN 		I_RUN_ID 				BIGINT,
	IN		I_INPV_DATABASE VARCHAR(128) , --GPROD1V_INP ,  _GPROD1V_INP
	IN		I_TARGET_DATABASE  VARCHAR(128), --GPROD1T_BASE ,  _GPROD1T_BASE
	IN		I_SRCI_DATABASE  VARCHAR(128) ,--GPROD1T_SRCI ,  _GPROD1T_SRCI
	IN      I_STG_DATABASE VARCHAR(128) ,--GPROD1T_STG ,  _GPROD1T_STG
	OUT 	O_ROWS_INSERTED_COUNT FLOAT,
	OUT 	O_ROWS_UPDATED_COUNT FLOAT,
	OUT 	O_ROWS_DELETED_COUNT FLOAT,
    OUT  	O_RETURN_CODE  			INTEGER,
    OUT  	O_RETURN_MSG 			VARCHAR(5000),
    OUT 	o_run_id 				BIGINT
    )

	/*
	###################################################################################################################################################################
	------------------------------------------------------------------------------------------------------------------------------------------------------------------
	#  Version History
	------------------------------------------------------------------------------------------------------------------------------------------------------------------
	#  Version 		|	Date        				 |	Author				|	COMMENT
	#  1.0        		| 	06 DEC,  2023 		| 	Omar HOSNY			|	Initial
	------------------------------------------------------------------------------------------------------------------------------------------------------------------
	###################################################################################################################################################################
	*/
	------------------------------------------------------------------------------------------------------------------------------------------------------------------
	-- Definition Of Procedure: RELOADS ALREADY PROCESSED DATA LOAD BY LOAD FOR A SPECIFIC PROCESS

	-- WHEN TO USE:
		-- INPUT VIEW IS EDITED AND DATA NEEDS TO BE RELOADED
		-- A NEW INPUT VIEW IS ADDED AND DATA NEEDS TO BE LOADED FOR ALL THE ALREADY PROCESSED LOADS
	-- HOW TO USE:
		-- CALL GPROD1_ETL.PROCESS_RELOADING(PROCESS NAME,AFFECTED TABLES,RUN ID,OUT_ROWS_INSERTED_COUNT, OUT_ROWS_UPDATED_COUNT, OUT_ROWS_DELETED_COUNT, OUT_RETURN_CODE, OUT_RETURN_MSG, OUT_RUN_ID);
			-- EXAMPLE: CALL GPROD1_ETL.PROCESS_RELOADING('TXF_CORE_L1_PRTY_L0_IDA_INSURANCE_ISSUERS', 'IDA_INSURANCE_ISSUERS',4272220534,A,B,C,D,E,F);
	-- HIGH LEVEL LOGIC:
		-- CHECK THAT THE PROVIDED PROCESS NAME IS NOT NULL AND EXISTS IN METADATA
		-- CHECK THAT THE PROVIDED AFFECTED TABLES IS NOT NULL,EXIST IN METADATA AND ACTIVE
		-- FOR EACH PROCESSED LOAD
			-- FOR EACH AFFECTED TABLE
				-- RUN STG LOADING FOR THE AFFECTED TABLE AND AFFECTED LOAD
				-- RUN SRCI LOADING FOR THE AFFECTED TABLE AND AFFECTED LOAD
			-- RUN PROCESS LOADING FOR THE PROCESS


	-- IMPORTANT NOTE: YOU NEED TO DELETE THE DATA IN THE BASE LAYER AFFECTED BY THIS PROCESS BEFORE USING THE PROCESS_RELOADING STORED PROCEDURE
	------------------------------------------------------------------------------------------------------------------------------------------------------------------

	BEGIN

		DECLARE 	V_SOURCE_NAME VARCHAR(200);
		DECLARE 	V_PROCESS_NAME VARCHAR(200);
		DECLARE 	V_BASE_TABLE VARCHAR(200);
		DECLARE 	V_APPLY_TYPE VARCHAR(100);
		DECLARE 	V_LOADING_TYPE VARCHAR(100);
		DECLARE		V_AFFECTED_TABLES VARCHAR(200) DEFAULT 'AFFECTED_TABLES_TMP';
	    DECLARE 	V_RETURN_CODE INTEGER DEFAULT 0;
	    DECLARE 	V_RETURN_MSG VARCHAR(5000) DEFAULT 'Process Completed Successfully';
		DECLARE 	V_DBC_RETURN_CODE INTEGER;
		DECLARE 	V_DBC_RETURN_MSG VARCHAR(1000);
		DECLARE		V_DBC_RUN_ID BIGINT DEFAULT 123;
		DECLARE 	V_INSERTED_ROWS_COUNT,V_UPDATED_ROWS_COUNT,V_DELETED_ROWS_COUNT,V_DBC_ROWS_COUNT FLOAT DEFAULT 0;
		DECLARE		V_AFFECTED_TABLES_CNT INTEGER;
/*		DECLARE		I_INPV_DATABASE VARCHAR(128) DEFAULT 'GPROD1V_INP';
		DECLARE		I_TARGET_DATABASE  VARCHAR(128) DEFAULT 'GPROD1T_BASE';
		DECLARE		I_SRCI_DATABASE  VARCHAR(128) DEFAULT 'GPROD1T_SRCI'; */
		DECLARE		V_CREATE_TABLE_STMNT VARCHAR(2000);
		DECLARE		V_DROP_TABLE_STMNT VARCHAR(2000);
		DECLARE		V_CLEAN_STG_STMNT VARCHAR(2000);
		DECLARE		V_RUN_ID BIGINT DEFAULT 123;
		DECLARE 	V_DBC_ROWS_INSERTED_COUNT	FLOAT;
		DECLARE 	V_DBC_ROWS_UPDATED_COUNT	FLOAT;
		DECLARE 	V_DBC_ROWS_DELETED_COUNT	FLOAT;


		MAINBLOCK:
		BEGIN

		--SET THE DROP TABLE STMT
		SET V_DROP_TABLE_STMNT = 'DROP TABLE ' || V_AFFECTED_TABLES || ';';

		-- GENERATE RUN ID
			IF i_run_id IS NULL THEN
				select GPROD1_ETL.GENERATE_RUN_ID()
				into v_run_id;
			ELSE
				SET v_run_id=	i_run_id;
			END IF;

		-- VALIDATE AFFECTED TABLES IS NOT NULL
			IF i_AFFECTED_TABLES IS NULL
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'AFFECTED TABLES CAN NOT BE NULL!';
            	leave MAINBLOCK;
            end if;

		-- VALIDATE  I_INPV_DATABASE
/*			IF I_INPV_DATABASE IS NULL OR I_INPV_DATABASE NOT IN ('GPROD1V_INP' , '_GPROD1V_INP')
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'INPV_DATABASE PARAMETER CAN ONLY BE ONE OF THOSE VALUES (GPROD1V_INP ,  _GPROD1V_INP) ';
            	leave MAINBLOCK;
            end if;*/

			IF I_INPV_DATABASE <> ( select src_db from GPROD1_ETL.LAYERS WHERE  layer_name = 'CORE' )
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'INPV_DATABASE SHOULD MATCH SRC_DB IN GPROD1_ETL.LAYERS ';
            	leave MAINBLOCK;
            end if;

		-- VALIDATE  I_TARGET_DATABASE
/*			IF I_TARGET_DATABASE IS NULL OR I_TARGET_DATABASE NOT IN ('GPROD1T_BASE' , '_GPROD1T_BASE')
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'TARGET_DATABASE PARAMETER CAN ONLY BE ONE OF THOSE VALUES (GPROD1T_BASE ,  _GPROD1T_BASE) ';
            	leave MAINBLOCK;
            end if;			*/

			IF I_TARGET_DATABASE <> ( select lyr_db from GPROD1_ETL.LAYERS WHERE  layer_name = 'CORE' )
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'TARGET_DATABASE SHOULD MATCH LYR_DB IN GPROD1_ETL.LAYERS ';
            	leave MAINBLOCK;
            end if;

		-- VALIDATE  I_SRCI_DATABASE
/*			IF I_SRCI_DATABASE IS NULL OR I_SRCI_DATABASE NOT IN ('GPROD1T_SRCI' , '_GPROD1T_SRCI')
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'SRCI_DATABASE PARAMETER CAN ONLY BE ONE OF THOSE VALUES (GPROD1T_SRCI ,  _GPROD1T_SRCI) ';
            	leave MAINBLOCK;
            end if;
			*/
			IF I_SRCI_DATABASE <> ( select lyr_db from GPROD1_ETL.LAYERS WHERE  layer_name = 'SRCI' )
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'SRCI_DATABASE SHOULD MATCH LYR_DB IN GPROD1_ETL.LAYERS ';
            	leave MAINBLOCK;
            end if;

		-- VALIDATE  I_STG_DATABASE
/*			IF I_STG_DATABASE IS NULL OR I_STG_DATABASE NOT IN ('GPROD1T_STG' , '_GPROD1T_STG')
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'STG_DATABASE PARAMETER CAN ONLY BE ONE OF THOSE VALUES (GPROD1T_STG ,  _GPROD1T_STG) ';
            	leave MAINBLOCK;
            end if;
			*/
			IF I_STG_DATABASE <> ( select lyr_db from GPROD1_ETL.LAYERS WHERE  layer_name = 'STG' )
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'STG_DATABASE SHOULD MATCH LYR_DB IN GPROD1_ETL.LAYERS ';
            	leave MAINBLOCK;
            end if;

			-- VALIDATE THAT THE PROCESS EXISTS
			SEL
				B.LOADING_MODE,
				A.SOURCE_NAME,
				A.PROCESS_NAME,
				A.TGT_TABLE,
				A.APPLY_TYPE
			FROM GPROD1_ETL.PROCESS A
			INNER JOIN GPROD1_ETL.SOURCE_SYSTEMS B
			ON A.SOURCE_NAME = B.SOURCE_NAME
			AND A.PROCESS_NAME = i_PROCESS_NAME
			INTO V_LOADING_TYPE, V_SOURCE_NAME, V_PROCESS_NAME, V_BASE_TABLE, V_APPLY_TYPE;

			IF V_PROCESS_NAME IS NULL
			THEN
            	SET V_RETURN_CODE = -1;
            	SET V_RETURN_MSG = 'INVALID PROCESS NAME!';
            	leave MAINBLOCK;
            end if;

		HANDLERBLOCK:
		BEGIN
			DECLARE EXIT HANDLER FOR SQLEXCEPTION
			BEGIN
		        SET V_RETURN_CODE = SQLCODE;
				GET DIAGNOSTICS EXCEPTION 1 V_RETURN_MSG = MESSAGE_TEXT;
				SET o_RETURN_CODE  = V_RETURN_CODE;
				SET o_RETURN_MSG = V_RETURN_MSG;

				-- DROP TABLE
				CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(
						V_DROP_TABLE_STMNT--i_SQL_SCRIPT
						,329 --i_SCRIPT_SEQ
						,v_run_id --i_run_id
						,'PROCESS_RELOADING'--i_SOURCE_NAME		VARCHAR(50),
						,'DROP AFFECTED TABLES TEMP TABLE'--i_PROCESS_NAME		VARCHAR(500),
						,NULL --i_LOAD_ID			VARCHAR(100),
						, 1 --i_log				integer, -- 1 log , 0 dont log
						,V_DBC_RETURN_CODE --o_RETURN_CODE    	INTEGER,
						,V_DBC_RETURN_MSG --o_RETURN_MSG  		VARCHAR(10000),
						,V_DBC_ROWS_COUNT --o_Rows_Count 		float,
						,V_DBC_RUN_ID --o_run_id 			BIGINT
					);

	    END;
	END;
			SET V_CREATE_TABLE_STMNT = 'CREATE MULTISET VOLATILE TABLE ' || V_AFFECTED_TABLES || ' AS (

			WITH TABLES AS (SEL ''' || i_AFFECTED_TABLES || ''' AFFECTED_TABLES WHERE ''' || i_AFFECTED_TABLES || ''' IS NOT NULL)
			, OUTPUT AS (
				select d.* from table (STRTOK_SPLIT_TO_TABLE(1, TABLES.AFFECTED_TABLES, '','')
				returns (outkey integer, TABLE_NUM integer, TABLE_NAME varchar(250) character set unicode) ) as d)
			SEL A.TABLE_NUM, TRIM(A.TABLE_NAME) TABLE_NAME
			FROM OUTPUT A
			INNER JOIN GPROD1_ETL.SOURCE_SYSTEM_TABLES B
			ON TRIM(A.TABLE_NAME) = B.TABLE_NAME
			AND B.ACTIVE = 1) WITH DATA ON COMMIT PRESERVE ROWS;';

			/*--SET THE DROP TABLE STMT
			SET V_DROP_TABLE_STMNT = 'DROP TABLE ' || V_AFFECTED_TABLES || ';';*/


			CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(
				V_CREATE_TABLE_STMNT--i_SQL_SCRIPT
				,0 --i_SCRIPT_SEQ
				,v_run_id --i_run_id
				,'PROCESS_RELOADING'--i_SOURCE_NAME		VARCHAR(50),
				,'CREATE AFFECTED TABLES TEMP TABLE' --V_PROCESS_NAME--i_PROCESS_NAME		VARCHAR(500),
				,NULL --i_LOAD_ID			VARCHAR(100),
				, 1 --i_log				integer, -- 1 log , 0 dont log
				,V_DBC_RETURN_CODE --o_RETURN_CODE    	INTEGER,
				,V_DBC_RETURN_MSG --o_RETURN_MSG  		VARCHAR(10000),
				,V_DBC_ROWS_COUNT --o_Rows_Count 		float,
				,V_DBC_RUN_ID --o_run_id 			BIGINT
			);

			 IF V_DBC_RETURN_CODE <> 0 THEN
			 	SET V_RETURN_CODE = V_DBC_RETURN_CODE;
			 	SET V_RETURN_MSG = V_DBC_RETURN_MSG;
			 	LEAVE MainBlock;
			 END IF;

			CALL GPROD1_ETL.COUNT_ROWS (
				NULL --in I_DB 			VARCHAR (200),
				,V_AFFECTED_TABLES --in I_TBL 			VARCHAR (200),
				, NULL --in I_QUERY 			VARCHAR (5000),
				,V_AFFECTED_TABLES_CNT --out O_CNT 			FLOAT,
				, V_DBC_RETURN_CODE --out O_RETURN_CODE 	INTEGER,
				, V_DBC_RETURN_MSG --out O_RETURN_MSG 	VARCHAR (5000)
			);
			IF V_DBC_RETURN_CODE <> 0 THEN
				SET V_RETURN_CODE = V_DBC_RETURN_CODE;
				SET V_RETURN_MSG = V_DBC_RETURN_MSG;
				--SET V_RETURN_MSG = 'HELLOOOO';
				LEAVE MainBlock;
			 END IF;

			--SEL COUNT(1) FROM V_AFFECTED_TABLES INTO V_AFFECTED_TABLES_CNT;
			-- VALIDATE AFFECTED TABLES EXIST IN METADATA
			IF V_AFFECTED_TABLES_CNT = 0 THEN
	        	SET V_RETURN_CODE = -1;
	        	SET V_RETURN_MSG = 'AFFECTED TABLES DO NOT EXIST IN METADATA';
	        	leave MAINBLOCK;
			END IF;


			-- INITIALIZE OUTPUT COUNTERS
			SET V_DELETED_ROWS_COUNT = 0;
			SET V_UPDATED_ROWS_COUNT = 0;
			SET V_INSERTED_ROWS_COUNT = 0;

			-- DELETE DATA FROM TERADATA STG
			FOR X AS X1 CURSOR FOR
				WITH TABLES AS (SEL i_AFFECTED_TABLES  AFFECTED_TABLES WHERE  i_AFFECTED_TABLES IS NOT NULL)
				, OUTPUT AS (
					select d.* from table (STRTOK_SPLIT_TO_TABLE(1, TABLES.AFFECTED_TABLES, ',')
					returns (outkey integer, TABLE_NUM integer, TABLE_NAME varchar(250) character set unicode) ) as d)
				SEL A.TABLE_NUM, TRIM(A.TABLE_NAME) TABLE_NAME
				FROM OUTPUT A
				INNER JOIN GPROD1_ETL.SOURCE_SYSTEM_TABLES B
				ON TRIM(A.TABLE_NAME) = B.TABLE_NAME
				AND B.ACTIVE = 1
				DO
					SET V_CLEAN_STG_STMNT = 'DEL FROM ' || I_SRCI_DATABASE || '.' || X.TABLE_NAME || ';';
					CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(
						V_CLEAN_STG_STMNT--i_SQL_SCRIPT
						,1 --i_SCRIPT_SEQ
						,v_run_id --i_run_id
						,'PROCESS_RELOADING'--i_SOURCE_NAME		VARCHAR(50),
						,'CLEAN_SRCI_' || X.TABLE_NAME--i_PROCESS_NAME		VARCHAR(500),
						,NULL --i_LOAD_ID			VARCHAR(100),
						, 1 --i_log				integer, -- 1 log , 0 dont log
						,V_DBC_RETURN_CODE --o_RETURN_CODE    	INTEGER,
						,V_DBC_RETURN_MSG --o_RETURN_MSG  		VARCHAR(10000),
						,V_DBC_ROWS_COUNT --o_Rows_Count 		float,
						,V_DBC_RUN_ID --o_run_id 			BIGINT
					);
					--CALL GPROD1P_PP.DBC_SYSEXECSQL_WITH_LOG(V_CLEAN_STG_STMNT,12,V_RUN_ID,'DELETE STG ' || X.TABLE_NAME,NULL,NULL,1/*1 log or 0 don't*/,V_DBC_RETURN_CODE,V_DBC_RETURN_MSG,V_DBC_ROWS_COUNT);
					IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
						LEAVE MainBlock;
					END IF;

					-- INCREMENT DELETED ROWS COUNT OUTPUT PARAMETER
					SET V_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT + V_DBC_ROWS_COUNT;

			END FOR;



			-- LOOP OVER LOADED LOADS FOR THE SOURCE ORDERED ASCENDINGLY
			FOR X AS X1 CURSOR FOR
				SEL
					LOAD_ID , MIN(BATCH_ID) MIN_BATCH_ID
				FROM GPROD1_ETL.CDC_AUDIT
				WHERE SOURCE_NAME = V_SOURCE_NAME
				AND VALID_BATCH = 1
				AND PROCESSED = 1
				GROUP BY LOAD_ID
				ORDER BY MIN_BATCH_ID
			DO
				-- FOR EACH TABLE
				FOR Y AS Y1 CURSOR FOR
				WITH TABLES AS (SEL i_AFFECTED_TABLES  AFFECTED_TABLES WHERE  i_AFFECTED_TABLES IS NOT NULL)
				, OUTPUT AS (
					select d.* from table (STRTOK_SPLIT_TO_TABLE(1, TABLES.AFFECTED_TABLES, ',')
					returns (outkey integer, TABLE_NUM integer, TABLE_NAME varchar(250) character set unicode) ) as d)
				SEL A.TABLE_NUM, TRIM(A.TABLE_NAME) TABLE_NAME
				FROM OUTPUT A
				INNER JOIN GPROD1_ETL.SOURCE_SYSTEM_TABLES B
				ON TRIM(A.TABLE_NAME) = B.TABLE_NAME
				AND B.ACTIVE = 1
				DO
					-- CALL STG LOADING
					CALL GPROD1_ETL.STG_LOADING(
					    V_SOURCE_NAME--IN 		i_SOURCE_NAME  			VARCHAR(200),
					    ,Y.TABLE_NAME --IN 		i_TABLE_NAME  			VARCHAR(200),
					    ,V_RUN_ID --IN 		I_RUN_ID 				BIGINT,
					    ,X.LOAD_ID --IN		I_LOAD_ID				VARCHAR(500),
					    ,1 --IN		I_RELOAD				INTEGER, /* 1 RELOAD ALL LOADS WHICH LOADED SUCCESSFULLY BEFORE, 0 IGNORE*/
					    ,0 --IN		I_ALL_BATCHES			INTEGER, /* 1 INCLUDES BATCH_ID COLUMN AS A KEY, SO IT GRASPS ALL DATA FROM ALL BATCHES, 0 IGNORE*/
					    ,V_DBC_ROWS_INSERTED_COUNT --OUT  	O_ROWS_INSERTED_COUNT	FLOAT,
					    ,V_DBC_ROWS_UPDATED_COUNT --OUT  	O_ROWS_UPDATED_COUNT	FLOAT,
					    ,V_DBC_ROWS_DELETED_COUNT -- OUT  	O_ROWS_DELETED_COUNT	FLOAT,
					    ,V_DBC_RETURN_CODE --OUT  	O_RETURN_CODE  			INTEGER,
					    ,V_DBC_RETURN_MSG-- OUT  	O_RETURN_MSG 			VARCHAR(5000),
					    ,V_DBC_RUN_ID --OUT 	o_run_id 				BIGINT
    				);

					IF V_DBC_RETURN_CODE <> 0 THEN
							SET V_RETURN_CODE = V_DBC_RETURN_CODE;
							SET V_RETURN_MSG = V_DBC_RETURN_MSG;
							LEAVE MainBlock;
					END IF;

					--INCREMENT OUTPUT COUNTERS
					SET V_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT + V_DBC_ROWS_DELETED_COUNT;
					SET V_UPDATED_ROWS_COUNT = V_UPDATED_ROWS_COUNT + V_DBC_ROWS_UPDATED_COUNT;
					SET V_INSERTED_ROWS_COUNT = V_INSERTED_ROWS_COUNT + V_DBC_ROWS_INSERTED_COUNT;

					-- CALL SRCI LOADING
					CALL GPROD1_ETL.SRCI_LOADING (
						V_SOURCE_NAME--IN 		i_SOURCE_NAME  			VARCHAR(200),
					    ,Y.TABLE_NAME --IN 		i_TABLE_NAME  			VARCHAR(200),
					    ,V_RUN_ID --IN 		I_RUN_ID 				BIGINT,
					    ,X.LOAD_ID --IN		I_LOAD_ID				VARCHAR(500),
						,0 --I_ALL_BATCHES			INTEGER, /* 1 INCLUDES BATCH_ID COLUMN AS A KEY, SO IT GRASPS ALL DATA FROM ALL BATCHES, 0 IGNORE*/
					    ,V_DBC_ROWS_INSERTED_COUNT --OUT  	O_ROWS_INSERTED_COUNT	FLOAT,
					    ,V_DBC_ROWS_UPDATED_COUNT --OUT  	O_ROWS_UPDATED_COUNT	FLOAT,
					    ,V_DBC_ROWS_DELETED_COUNT -- OUT  	O_ROWS_DELETED_COUNT	FLOAT,
					    ,V_DBC_RETURN_CODE --OUT  	O_RETURN_CODE  			INTEGER,
					    ,V_DBC_RETURN_MSG-- OUT  	O_RETURN_MSG 			VARCHAR(5000),
					    ,V_DBC_RUN_ID --OUT 	o_run_id 				BIGINT
    				);
					IF V_DBC_RETURN_CODE <> 0 THEN
							SET V_RETURN_CODE = V_DBC_RETURN_CODE;
							SET V_RETURN_MSG = V_DBC_RETURN_MSG;
							LEAVE MainBlock;
					END IF;

					--INCREMENT OUTPUT COUNTERS
					SET V_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT + V_DBC_ROWS_DELETED_COUNT;
					SET V_UPDATED_ROWS_COUNT = V_UPDATED_ROWS_COUNT + V_DBC_ROWS_UPDATED_COUNT;
					SET V_INSERTED_ROWS_COUNT = V_INSERTED_ROWS_COUNT + V_DBC_ROWS_INSERTED_COUNT;

				END FOR; --INNER LOOP


			-- CALL PROCESS
			--DEL FROM GPROD1T_BASE.GEOGRCL_AREA WHERE COALESCE(UPDATE_PROCESS_NAME,PROCESS_NAME) = 'TXF_CORE_L1_GEOGRCL_AREA_L0_Vaccine_Village';
			--CALL GPROD1P_PP.PROCESS_LOADING('GPROD1V_INP','GPROD1T_BASE','GEOGRCL_AREA','TXF_CORE_L1_GEOGRCL_AREA_L0_Vaccine_Village',NULL,'202310221748195400','VACCINE',NULL, NULL ,NULL,O1,O2,O3);
			CALL	GPROD1_ETL.EDW_PROCESS_LOADING(
			    V_PROCESS_NAME --IN 		I_PROCESSNAME  			VARCHAR(1000),
			    ,V_APPLY_TYPE --IN 		I_APPLY_TYPE  			VARCHAR(500),
			    ,V_run_id --IN 		I_RUN_ID 				BIGINT,
			    ,X.LOAD_ID --IN		I_LOAD_ID				VARCHAR(500),
				,1 --IN		I_DELTA_MODE			INTEGER,
			    ,V_DBC_ROWS_INSERTED_COUNT --OUT  	O_ROWS_INSERTED_COUNT	FLOAT,
			    ,V_DBC_ROWS_UPDATED_COUNT --OUT  	O_ROWS_UPDATED_COUNT	FLOAT,
			    ,V_DBC_ROWS_DELETED_COUNT -- OUT  	O_ROWS_DELETED_COUNT	FLOAT,
			    ,V_DBC_RETURN_CODE --OUT  	O_RETURN_CODE  			INTEGER,
			    ,V_DBC_RETURN_MSG-- OUT  	O_RETURN_MSG 			VARCHAR(5000),
			    ,V_DBC_RUN_ID --OUT 	o_run_id 				BIGINT
			    );

				IF V_DBC_RETURN_CODE <> 0 THEN
						SET V_RETURN_CODE = V_DBC_RETURN_CODE;
						SET V_RETURN_MSG = V_DBC_RETURN_MSG;
						LEAVE MainBlock;
				END IF;

				--INCREMENT OUTPUT COUNTERS
				SET V_DELETED_ROWS_COUNT = V_DELETED_ROWS_COUNT + V_DBC_ROWS_DELETED_COUNT;
				SET V_UPDATED_ROWS_COUNT = V_UPDATED_ROWS_COUNT + V_DBC_ROWS_UPDATED_COUNT;
				SET V_INSERTED_ROWS_COUNT = V_INSERTED_ROWS_COUNT + V_DBC_ROWS_INSERTED_COUNT;

			END FOR; --OUTER LOOP


			-- DROP TABLE
			CALL GPROD1_ETL.DBC_SYSEXECSQL_WITH_LOG(
					V_DROP_TABLE_STMNT--i_SQL_SCRIPT
					,329 --i_SCRIPT_SEQ
					,v_run_id --i_run_id
					,'PROCESS_RELOADING'--i_SOURCE_NAME		VARCHAR(50),
					,'DROP AFFECTED TABLES TEMP TABLE'--i_PROCESS_NAME		VARCHAR(500),
					,NULL --i_LOAD_ID			VARCHAR(100),
					, 1 --i_log				integer, -- 1 log , 0 dont log
					,V_DBC_RETURN_CODE --o_RETURN_CODE    	INTEGER,
					,V_DBC_RETURN_MSG --o_RETURN_MSG  		VARCHAR(10000),
					,V_DBC_ROWS_COUNT --o_Rows_Count 		float,
					,V_DBC_RUN_ID --o_run_id 			BIGINT
				);

			IF V_DBC_RETURN_CODE <> 0 THEN
			 	SET V_RETURN_CODE = V_DBC_RETURN_CODE;
			 	SET V_RETURN_MSG = V_DBC_RETURN_MSG;
			 	LEAVE MainBlock;
			END IF;
		END; --MAINBLOCK

		-- SET OUTPUT PARAMETERS
		SET O_RETURN_CODE = V_RETURN_CODE;
    	SET O_RETURN_MSG = V_RETURN_MSG;
		SET O_ROWS_DELETED_COUNT = V_DELETED_ROWS_COUNT;
		SET O_ROWS_UPDATED_COUNT = V_UPDATED_ROWS_COUNT;
		SET O_ROWS_INSERTED_COUNT = V_INSERTED_ROWS_COUNT;
